"""
backend/src/audit_ledger/approval_lock.py
==========================================
G4 — Atomic Single-Use Approval Lock using SQLite WAL mode.

Design goals
------------
* Zero-Docker: uses Python's built-in ``sqlite3`` with WAL journal mode so the
  same logic runs in CI without PostgreSQL.
* Mirrors the PostgreSQL conditional-UPDATE pattern exactly, so a later migration
  to Postgres requires only a driver swap.
* A threading.Lock serialises concurrent writers on a *single shared connection*
  (the typical in-process / in-memory CI scenario); this gives the same
  "exactly one winner" guarantee as ``SELECT ... FOR UPDATE`` in Postgres.
  For file-backed databases with one connection per thread, ``BEGIN IMMEDIATE``
  achieves the same at the SQLite level.
* The ``approval_token`` is consumed (status set to ``'APPROVED'``) atomically;
  no second call can observe ``status = 'PENDING'`` for the same token.

Invariant G4 (from AGENTS.md)
------------------------------
  * ``cursor.rowcount == 1`` after the conditional UPDATE → HTTP 200 APPROVED.
  * ``rowcount != 1``        → HTTP 409 TOKEN_ALREADY_USED_OR_EXPIRED.
  * The ``approval_token`` is never reissued.

No LLM libraries are imported — deterministic-core safe.
"""

from __future__ import annotations

import sqlite3
import threading
import weakref
from datetime import datetime, timezone

# Per-connection write lock registry.
# Maps connection id → Lock so the same connection object always uses the same
# lock regardless of which thread calls consume_approval_token or create_pending_approval.
_conn_locks: weakref.WeakValueDictionary[int, threading.Lock] = (
    weakref.WeakValueDictionary()
)
_registry_mu = threading.Lock()


def _lock_for(conn: sqlite3.Connection) -> threading.Lock:
    """Return (or create) the write-serialisation lock for *conn*."""
    cid = id(conn)
    with _registry_mu:
        lock = _conn_locks.get(cid)
        if lock is None:
            lock = threading.Lock()
            _conn_locks[cid] = lock
    return lock


def _to_utc_iso(dt_str: str) -> str:
    """Normalize an ISO-8601 string to UTC ISO-8601 format for exact lexical comparison."""
    dt = datetime.fromisoformat(dt_str)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    else:
        dt = dt.astimezone(timezone.utc)
    return dt.isoformat()


# DDL ──────────────────────────────────────────────────────────────────────────
_CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS exception_approvals (
    approval_token    TEXT PRIMARY KEY,
    entity_id         TEXT NOT NULL,
    status            TEXT NOT NULL
                          CHECK(status IN ('PENDING','APPROVED','REJECTED','EXPIRED')),
    expires_at        TEXT NOT NULL,
    reviewed_by       TEXT,
    reviewed_at       TEXT,
    discrepancy_paise INTEGER DEFAULT 0,
    category          TEXT DEFAULT 'UNSPECIFIED'
);
"""

# PRAGMA / journal configuration ───────────────────────────────────────────────
_WAL_PRAGMAS = [
    "PRAGMA journal_mode = WAL;",
    "PRAGMA synchronous   = NORMAL;",   # Safe with WAL; faster than FULL.
    "PRAGMA busy_timeout  = 5000;",     # 5 s retry on SQLITE_BUSY before error.
]


# ─────────────────────────────────────────────────────────────────────────────
# Schema bootstrap
# ─────────────────────────────────────────────────────────────────────────────

def initialise_schema(conn: sqlite3.Connection) -> None:
    """Create the ``exception_approvals`` table if it does not already exist.

    Call once per connection (or at application startup) before any other
    function in this module.
    """
    for pragma in _WAL_PRAGMAS:
        conn.execute(pragma)
    conn.execute(_CREATE_TABLE_SQL)

    # Safe migration for existing schemas lacking metadata columns
    cursor = conn.execute("PRAGMA table_info(exception_approvals)")
    columns = {row[1] for row in cursor.fetchall()}
    if "discrepancy_paise" not in columns:
        conn.execute("ALTER TABLE exception_approvals ADD COLUMN discrepancy_paise INTEGER DEFAULT 0")
    if "category" not in columns:
        conn.execute("ALTER TABLE exception_approvals ADD COLUMN category TEXT DEFAULT 'UNSPECIFIED'")

    conn.commit()


# ─────────────────────────────────────────────────────────────────────────────
# Public API
# ─────────────────────────────────────────────────────────────────────────────

def create_pending_approval(
    conn: sqlite3.Connection,
    approval_token: str,
    entity_id: str,
    expires_at_iso: str,
    discrepancy_paise: int = 0,
    category: str = "UNSPECIFIED",
) -> None:
    """Insert a new approval record in ``PENDING`` status.

    Parameters
    ----------
    conn:
        An open ``sqlite3.Connection``.
    approval_token:
        UUID4 generated by the caller. Must be unique.
    entity_id:
        The identifier of the exception / entity being approved.
    expires_at_iso:
        ISO-8601 timestamp string after which the token is considered expired.
        Normalized to UTC ISO-8601 format prior to persistence.
    discrepancy_paise:
        Amount in smallest currency subunit (paise).
    category:
        Discrepancy category identifier.
    """
    write_lock = _lock_for(conn)
    norm_expires = _to_utc_iso(expires_at_iso)

    with write_lock:
        in_tx_already = conn.in_transaction
        if not in_tx_already:
            conn.execute("BEGIN IMMEDIATE")
        try:
            conn.execute(
                """
                INSERT INTO exception_approvals
                    (approval_token, entity_id, status, expires_at, discrepancy_paise, category)
                VALUES (?, ?, 'PENDING', ?, ?, ?)
                """,
                (approval_token, entity_id, norm_expires, discrepancy_paise, category),
            )
            if not in_tx_already:
                conn.execute("COMMIT")
            else:
                conn.commit()
        except Exception:
            if not in_tx_already:
                conn.execute("ROLLBACK")
            else:
                conn.rollback()
            raise


def consume_approval_token(
    conn: sqlite3.Connection,
    approval_token: str,
    reviewer: str,
    now_iso: str,
) -> tuple[bool, int, str]:
    """Atomically consume a ``PENDING`` approval token.

    Uses a per-connection threading.Lock to serialise concurrent callers that
    share the same connection object.

    Parameters
    ----------
    conn:
        An open ``sqlite3.Connection`` (``check_same_thread=False``).
    approval_token:
        The UUID4 token to consume.
    reviewer:
        Human-readable identifier of the approver.
    now_iso:
        Current timestamp as ISO-8601 string. Normalized to UTC ISO-8601 format
        before comparison and storage.

    Returns
    -------
    tuple[bool, int, str]
        ``(True,  200, "APPROVED")``                       — exactly one row updated.
        ``(False, 409, "TOKEN_ALREADY_USED_OR_EXPIRED")``  — zero rows updated.
    """
    write_lock = _lock_for(conn)
    norm_now = _to_utc_iso(now_iso)

    with write_lock:
        in_tx_already = conn.in_transaction

        if not in_tx_already:
            conn.execute("BEGIN IMMEDIATE")

        try:
            cursor = conn.execute(
                """
                UPDATE exception_approvals
                   SET status      = 'APPROVED',
                       reviewed_by = ?,
                       reviewed_at = ?
                 WHERE approval_token = ?
                   AND status         = 'PENDING'
                   AND expires_at     > ?
                """,
                (reviewer, norm_now, approval_token, norm_now),
            )
            rows_updated: int = cursor.rowcount

            if not in_tx_already:
                conn.execute("COMMIT")
            else:
                conn.commit()

        except Exception:
            if not in_tx_already:
                conn.execute("ROLLBACK")
            else:
                conn.rollback()
            raise

    # G4 invariant: rowcount must be 0 or 1.
    assert rows_updated in (0, 1), (  # noqa: S101
        f"Unexpected rowcount={rows_updated} from conditional UPDATE"
    )

    if rows_updated == 1:
        return (True, 200, "APPROVED")

    return (False, 409, "TOKEN_ALREADY_USED_OR_EXPIRED")
