"""
backend/src/verifier/factset_gate.py
======================================
G3 — Verbatim FactSet Provenance Verifier (100% deterministic, zero LLM imports).

Guarantees:
  * Every cited amount, UTR, entity ID, and FETERS purpose code in an LLM hypothesis
    is checked against the source-of-truth FactSetSnapshot allowlist.
  * proposed_rationale is scanned via regex for hallucinated entity IDs, UTRs,
    FETERS codes, and explicit rupee/paise figures.
  * If ANY token fails verification, the response status is ABSTAINED_UNGROUNDED
    with all ungrounded tokens returned.
  * Zero LLM imports — strictly deterministic core.
"""

from __future__ import annotations

import re
from typing import Literal
from pydantic import BaseModel, Field

# ── Regexes for entity IDs, UTRs, FETERS codes, and currency amounts ──────────
_RAZORPAY_ID_RE = re.compile(
    r"\b(?:pay|rfnd|trf|adj|order|setl)_[A-Za-z0-9]{8,20}\b"
)
_UTR_RE = re.compile(r"\bUTR[A-Z0-9]{6,22}\b")
_FETERS_RE = re.compile(r"\b[PS]\d{4}\b")
_RUPEE_RE = re.compile(r"((?:₹|INR\s?)\s*(\d[\d,]*(?:\.\d{1,2})?))")


# ── Pydantic models ───────────────────────────────────────────────────────────

class FactSetSnapshot(BaseModel):
    """Source-of-truth snapshot of allowed entities, amounts, UTRs, and codes."""

    entity_id: str
    allowed_amounts_paise: set[int] = Field(default_factory=set)
    allowed_utrs: set[str] = Field(default_factory=set)
    allowed_entity_ids: set[str] = Field(default_factory=set)
    allowed_feters_codes: set[str] = Field(default_factory=set)
    raw_context_text: str = ""


class VerificationResult(BaseModel):
    """Result of validating an LLM hypothesis against a FactSetSnapshot."""

    verified: bool
    status: Literal["FACTSET_VERIFIED", "ABSTAINED_UNGROUNDED"]
    ungrounded_tokens: list[str] = Field(default_factory=list)


# ── Internal helpers ─────────────────────────────────────────────────────────

def _is_amount_allowed(
    num_str: str,
    allowed_amounts_paise: set[int],
) -> bool:
    """Check whether a currency figure matches the allowed amounts.

    Normalizes rupee strings to integer paise (e.g. '1500' -> 150000,
    '1500.50' -> 150050) and also allows raw integer strings >= 1000
    matching allowed_amounts_paise directly (e.g. '150000' paise).
    """
    clean = num_str.replace(",", "")
    # Check 1: normalize standard rupee value to paise
    if "." in clean:
        parts = clean.split(".", 1)
        cents = (parts[1] + "00")[:2]
        paise = int(parts[0]) * 100 + int(cents)
    else:
        paise = int(clean) * 100

    if paise in allowed_amounts_paise:
        return True

    # Check 2: also allow raw integer strings >= 1000 matching allowed_amounts_paise directly
    try:
        raw_val = int(clean.split(".")[0])
        if raw_val >= 1000 and raw_val in allowed_amounts_paise:
            return True
    except ValueError:
        pass

    return False


# ── Public API ───────────────────────────────────────────────────────────────

def verify_hypothesis_against_factset(
    proposed_rationale: str,
    cited_amounts_paise: list[int],
    cited_utrs: list[str],
    cited_entity_ids: list[str],
    cited_feters_codes: list[str],
    factset: FactSetSnapshot,
) -> VerificationResult:
    """Verify all cited tokens and scanned rationale tokens against FactSet.

    Parameters
    ----------
    proposed_rationale:
        Free-text hypothesis rationale generated by an LLM or heuristic.
    cited_amounts_paise:
        Explicit list of monetary amounts cited in paise.
    cited_utrs:
        Explicit list of UTR tokens cited.
    cited_entity_ids:
        Explicit list of entity identifiers cited.
    cited_feters_codes:
        Explicit list of FETERS purpose codes cited.
    factset:
        Immutable source-of-truth FactSetSnapshot.

    Returns
    -------
    VerificationResult
        verified=True, status="FACTSET_VERIFIED" if all tokens are grounded.
        verified=False, status="ABSTAINED_UNGROUNDED", ungrounded_tokens=[...]
        if ANY token fails verification.
    """
    ungrounded_tokens: list[str] = []

    # Effective allowed entity IDs includes the snapshot entity_id itself
    effective_allowed_entity_ids = set(factset.allowed_entity_ids)
    if factset.entity_id:
        effective_allowed_entity_ids.add(factset.entity_id)

    # ── 1. Check explicit cited lists ─────────────────────────────────────────
    for amt in cited_amounts_paise:
        if amt not in factset.allowed_amounts_paise:
            token = str(amt)
            if token not in ungrounded_tokens:
                ungrounded_tokens.append(token)

    for utr in cited_utrs:
        if utr not in factset.allowed_utrs:
            if utr not in ungrounded_tokens:
                ungrounded_tokens.append(utr)

    for eid in cited_entity_ids:
        if eid not in effective_allowed_entity_ids:
            if eid not in ungrounded_tokens:
                ungrounded_tokens.append(eid)

    for code in cited_feters_codes:
        if code not in factset.allowed_feters_codes:
            if code not in ungrounded_tokens:
                ungrounded_tokens.append(code)

    # ── 2. Scan proposed_rationale for entity IDs ─────────────────────────────
    for m in _RAZORPAY_ID_RE.finditer(proposed_rationale):
        eid = m.group(0)
        if eid not in effective_allowed_entity_ids:
            if eid not in ungrounded_tokens:
                ungrounded_tokens.append(eid)

    # ── 3. Scan proposed_rationale for UTRs ───────────────────────────────────
    for m in _UTR_RE.finditer(proposed_rationale):
        utr = m.group(0)
        if utr not in factset.allowed_utrs:
            if utr not in ungrounded_tokens:
                ungrounded_tokens.append(utr)

    # ── 4. Scan proposed_rationale for FETERS purpose codes ───────────────────
    for m in _FETERS_RE.finditer(proposed_rationale):
        code = m.group(0)
        if code not in factset.allowed_feters_codes:
            if code not in ungrounded_tokens:
                ungrounded_tokens.append(code)

    # ── 5. Scan proposed_rationale for explicit rupee/paise figures ───────────
    for m in _RUPEE_RE.finditer(proposed_rationale):
        full_token = m.group(1).strip()
        num_str = m.group(2)
        if not _is_amount_allowed(num_str, factset.allowed_amounts_paise):
            if full_token not in ungrounded_tokens:
                ungrounded_tokens.append(full_token)

    # ── Decision ──────────────────────────────────────────────────────────────
    if ungrounded_tokens:
        return VerificationResult(
            verified=False,
            status="ABSTAINED_UNGROUNDED",
            ungrounded_tokens=ungrounded_tokens,
        )

    return VerificationResult(
        verified=True,
        status="FACTSET_VERIFIED",
        ungrounded_tokens=[],
    )
